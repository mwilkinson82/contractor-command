// SDK CLI's isolated SSR loader does not retain this app's PDFium WASM plugin.
// Generate the listing through the SDK's real transport, with the existing test
// asset aliases, then verify it with src/lib/mcp/manifest-sync.test.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { it, expect } from "vitest";
import { defineMcp } from "@lovable.dev/mcp-js";
import { createTanStackMcpHandler } from "@lovable.dev/mcp-js/stacks/tanstack";
import { ATHENA_TOOLS } from "../src/lib/mcp/index";
it("writes tool discovery schemas generated by the SDK", async () => {
  const manifest = JSON.parse(readFileSync(".lovable/mcp/manifest.json", "utf8"));
  const mcp = defineMcp({
    name: "athena",
    title: "Athena",
    version: manifest.mcp.server.version,
    instructions: "Generate discovery only.",
    tools: ATHENA_TOOLS,
    metrics: false,
  } as never);
  const handler = createTanStackMcpHandler(mcp, { resourcePath: "/mcp" });
  async function send(body: unknown) {
    const response = await handler({
      request: new Request("https://x/mcp", {
        method: "POST",
        headers: {
          "content-type": "application/json",
          accept: "application/json, text/event-stream",
        },
        body: JSON.stringify(body),
      }),
    });
    const raw = await response.text();
    return JSON.parse(
      raw.trimStart().startsWith("{")
        ? raw
        : raw
            .split("\n")
            .find((l) => l.startsWith("data:"))!
            .slice(5),
    );
  }
  await send({
    jsonrpc: "2.0",
    id: 1,
    method: "initialize",
    params: {
      protocolVersion: "2025-06-18",
      capabilities: {},
      clientInfo: { name: "local-manifest", version: "1" },
    },
  });
  const response = await send({ jsonrpc: "2.0", id: 2, method: "tools/list" });
  expect(response.result.tools.some((t: { name: string }) => t.name === "schedule_workflow")).toBe(
    true,
  );
  const generated = response.result.tools.map((t: Record<string, unknown>) => ({
    name: t.name,
    title: t.title,
    description: t.description,
    annotations: t.annotations,
    inputSchema: t.inputSchema,
    outputSchema: t.outputSchema ?? null,
    ...(t.conditional ? { conditional: true } : {}),
  }));
  const canonical = (v: unknown): unknown =>
    Array.isArray(v)
      ? v.map(canonical)
      : v && typeof v === "object"
        ? Object.fromEntries(
            Object.entries(v as Record<string, unknown>)
              .sort(([a], [b]) => a.localeCompare(b))
              .map(([k, x]) => [k, canonical(x)]),
          )
        : v;
  manifest.mcp.tools = manifest.mcp.tools.map((t: { name: string; inputSchema: unknown }) => {
    const schema = generated.find((x: { name: string }) => x.name === t.name)!.inputSchema;
    return JSON.stringify(canonical(schema)) === JSON.stringify(canonical(t.inputSchema))
      ? t
      : { ...t, inputSchema: schema };
  });
  for (const tool of generated)
    if (!manifest.mcp.tools.some((t: { name: string }) => t.name === tool.name))
      manifest.mcp.tools.push(tool);
  writeFileSync(".lovable/mcp/manifest.json", JSON.stringify(manifest, null, 2) + "\n");
});
